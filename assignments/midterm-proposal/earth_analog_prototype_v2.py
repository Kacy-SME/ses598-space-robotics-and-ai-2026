import cv2
import numpy as np
from PIL import Image

def detect_dice_mask(pil_img,
                     lower_hsv=(0, 120, 80),    # tune to your dice color
                     upper_hsv=(15, 255, 255),   # red dice example
                     min_area=200,
                     dilate_px=20):
    """
    Detect dice in a ground photo by color segmentation.
    Returns a binary mask (255=dice region) in numpy uint8.
    """
    img_bgr = cv2.cvtColor(np.array(pil_img), cv2.COLOR_RGB2BGR)
    hsv = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2HSV)

    mask = cv2.inRange(hsv, np.array(lower_hsv), np.array(upper_hsv))

    # For red, also catch the wraparound hue range
    mask2 = cv2.inRange(hsv, np.array([165, 120, 80]), np.array([180, 255, 255]))
    mask = cv2.bitwise_or(mask, mask2)

    # Remove tiny blobs
    contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    filtered = np.zeros_like(mask)
    for cnt in contours:
        if cv2.contourArea(cnt) >= min_area:
            cv2.drawContours(filtered, [cnt], -1, 255, -1)

    # Dilate to cover edges/shadows
    kernel = np.ones((dilate_px, dilate_px), np.uint8)
    dilated = cv2.dilate(filtered, kernel, iterations=1)
    return dilated

def inpaint_dice(pil_img, mask):
    """
    Inpaint the dice regions using Telea algorithm.
    Returns cleaned PIL Image.
    """
    img_bgr = cv2.cvtColor(np.array(pil_img), cv2.COLOR_RGB2BGR)
    inpainted = cv2.inpaint(img_bgr, mask, inpaintRadius=15, flags=cv2.INPAINT_TELEA)
    return Image.fromarray(cv2.cvtColor(inpainted, cv2.COLOR_BGR2RGB))

def remove_dice(pil_img, **kwargs):
    """Full pipeline: detect + inpaint. Returns (cleaned_pil, mask)."""
    mask = detect_dice_mask(pil_img, **kwargs)
    if mask.max() == 0:
        return pil_img, mask   # no dice found
    cleaned = inpaint_dice(pil_img, mask)
    return cleaned, mask

