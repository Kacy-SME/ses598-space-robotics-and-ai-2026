def is_valid_terrain_patch(pil_patch):
    arr = np.array(pil_patch.convert('L')).astype(np.float32) / 255.0
    if arr.mean() < 0.15 or arr.mean() > 0.85: return False
    if arr.std() < 0.04: return False
    grad = (np.abs(np.diff(arr, axis=1)).mean() + np.abs(np.diff(arr, axis=0)).mean()) / 2
    if grad < 0.02: return False
    return True

def extract_terrain_pairs(oh_img, rv_img,
                           oh_match_xy, rv_match_xy,
                           oh_dice_xys, rv_dice_xys,
                           n_pairs=20, patch_size=128,
                           scale_ratio=4.62, exclusion_radius=250):
    oh_W, oh_H = oh_img.size
    rv_W, rv_H = rv_img.size
    half_oh = patch_size // 2
    half_rv = int(patch_size * scale_ratio) // 2

    oh_mask = make_dice_mask_from_labels(oh_img.size, oh_dice_xys, exclusion_radius)
    rv_mask = make_dice_mask_from_labels(rv_img.size, rv_dice_xys, exclusion_radius)

    # Also exclude top portion of rover image (wall/background)
    # Estimate: dice are in lower ~60% of rover image — exclude above min dice y
    min_rv_y = min(y for x, y in rv_dice_xys)
    rv_mask[:max(0, min_rv_y - 400), :] = 255  # exclude sky/wall above terrain zone

    oh_cx, oh_cy = oh_match_xy
    rv_cx, rv_cy = rv_match_xy

    pairs = []
    attempts = 0

    while len(pairs) < n_pairs and attempts < 1000:
        attempts += 1
        dx = random.randint(-600, 600)
        dy = random.randint(-500, 500)

        ox = oh_cx + dx
        oy = oh_cy + dy
        if ox - half_oh < 0 or ox + half_oh >= oh_W: continue
        if oy - half_oh < 0 or oy + half_oh >= oh_H: continue
        if oh_mask[oy-half_oh:oy+half_oh, ox-half_oh:ox+half_oh].max() > 0: continue

        rx = rv_cx + int(dx * scale_ratio)
        ry = rv_cy + int(dy * scale_ratio)
        if rx - half_rv < 0 or rx + half_rv >= rv_W: continue
        if ry - half_rv < 0 or ry + half_rv >= rv_H: continue
        if rv_mask[ry-half_rv:ry+half_rv, rx-half_rv:rx+half_rv].max() > 0: continue

        oh_patch = oh_img.crop((ox-half_oh, oy-half_oh, ox+half_oh, oy+half_oh))
        rv_patch = rv_img.crop((rx-half_rv, ry-half_rv, rx+half_rv, ry+half_rv))

        if not is_valid_terrain_patch(oh_patch): continue
        if not is_valid_terrain_patch(rv_patch): continue

        pairs.append({
            'overhead': oh_patch.resize((224, 224)),
            'rover':    rv_patch.resize((224, 224)),
            'oh_xy': (ox, oy), 'rv_xy': (rx, ry)
        })

    return pairs

