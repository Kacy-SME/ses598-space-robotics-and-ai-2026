def weighted_infonce(orb_embs, gnd_embs, tp_weights, tau=0.07):
    sim = orb_embs @ gnd_embs.T / tau
    labels = torch.arange(sim.size(0), device=sim.device)
    loss = F.cross_entropy(sim, labels, reduction='none')
    w = tp_weights - tp_weights.min() + 0.1
    w = w / w.mean()
    return (loss * w).mean()

