# ── T(p) computation (same as Mars pipeline) ──────────────────────────────
def compute_tp(pil_patch):
    """Spectral entropy H(p) + phase congruency R(p) → T(p)."""
    arr = np.array(pil_patch.convert('L')).astype(np.float32) / 255.0

    # H(p): spectral entropy via SVD
    U, s, Vt = np.linalg.svd(arr, full_matrices=False)
    s_norm = s / (s.sum() + 1e-8)
    Hp = -np.sum(s_norm * np.log(s_norm + 1e-8))

    # R(p): gradient-based stability proxy (phase congruency approx)
    gx = np.abs(np.diff(arr, axis=1)).mean()
    gy = np.abs(np.diff(arr, axis=0)).mean()
    Rp = (gx + gy) / 2.0

    return float(Hp + Rp)

